"""Write COVERAGE.md: element counts per type vs the SRD 5.1 inventory."""
import json, glob, os, sys, collections, re
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lib import OUT, events, find_head, clean

def all_elements():
    for p in sorted(glob.glob(os.path.join(OUT, '**', '*.json'), recursive=True)):
        if p.endswith('pack.json'):
            continue
        d = json.load(open(p, encoding='utf-8'))
        for e in d.get('elements', []):
            yield os.path.relpath(p, OUT), e

def pdf_inventory():
    ev = events()
    inv = {}
    a = find_head('Magic Items A-Z'); b = find_head('Sentient Magic Items', None, a)
    inv['magic_headings'] = sum(1 for e in ev[a:b] if e['k'] == 'H' and e['size'] == 18)
    return inv

def main():
    els = list(all_elements())
    by_type = collections.Counter(e['type'] for _, e in els)
    by_file = collections.Counter(f for f, _ in els)
    inv = pdf_inventory()
    cls_feats = collections.Counter()
    rules = collections.Counter()
    for f, e in els:
        for r in e.get('rules', []):
            rules[r['kind']] += 1
    spells = [e for _, e in els if e['type'] == 'Spell']
    by_level = collections.Counter(next(s['value'] for s in e['setters'] if s['name'] == 'level') for e in spells)
    cls_lists = collections.Counter(c for e in spells for c in e.get('supports', []))
    mi = [e for _, e in els if e['type'] == 'Magic Item']
    mi_rules = sum(1 for e in mi if e.get('rules'))

    rows = [
        ('Race', 9, 'SRD "Races": dwarf, elf, halfling, human, dragonborn, gnome, half-elf, half-orc, tiefling'),
        ('Sub Race', 4, 'hill dwarf, high elf, lightfoot halfling, rock gnome'),
        ('Racial Trait', None, 'one element per mechanical or descriptive trait (draconic ancestries included)'),
        ('Class', 12, 'all twelve classes, levels 1-20'),
        ('Archetype', 12, 'the single SRD subclass of each class'),
        ('Class Feature', None, 'class features, fighting styles, metamagic, invocations, pact boons'),
        ('Archetype Feature', None, 'subclass features'),
        ('Background', 1, 'Acolyte'),
        ('Background Feature', 1, 'Shelter of the Faithful'),
        ('Feat', 1, 'Grappler'),
        ('Spell', 319, 'every spell entry in "Spell Descriptions"'),
        ('Weapon', 37, 'SRD weapons table'),
        ('Armor', 13, 'twelve armors and the shield'),
        ('Item', None, 'adventuring gear, tools, instruments, gaming sets, packs, mounts, tack, vehicles, trade goods'),
        ('Magic Item', None, f'{inv["magic_headings"]} headings in "Magic Items A-Z"; variants (+1/+2/+3) are separate elements, Spell Scroll is generated by the loader'),
        ('Condition', 15, 'SRD Appendix PH-A game conditions (rules/conditions.json), each with maps_to to the SRD 5.2.1 condition'),
        ('Source', 1, 'SRD 5.1 source record'),
    ]
    out = ['# srd-5.1 coverage', '',
           'Generated by `content-tools/srd51/build_coverage.py`. Counts are elements in `content/srd-5.1`.', '',
           '| Element type | Elements | SRD inventory | Notes |', '|---|---:|---:|---|']
    for t, n, note in rows:
        out.append(f'| {t} | {by_type.get(t, 0)} | {n if n is not None else "n/a"} | {note} |')
    out += ['', f'Total elements: {sum(by_type.values())}. Rules: ' + ', '.join(f'{k} {v}' for k, v in sorted(rules.items())) + '.', '',
            '## Spells by level', '', '| Level | Spells |', '|---|---:|']
    for lv in sorted(by_level, key=int):
        out.append(f'| {"Cantrip" if lv == "0" else lv} | {by_level[lv]} |')
    out += ['', '## Spells on class lists', '', '| Class | Spells |', '|---|---:|']
    for c, n in sorted(cls_lists.items()):
        out.append(f'| {c} | {n} |')
    out += ['', '## Files', '', '| File | Elements |', '|---|---:|']
    for f, n in sorted(by_file.items()):
        out.append(f'| `{f}` | {n} |')
    out += ['', f'Magic items carrying mechanical rules: {mi_rules} of {len(mi)}.', '', '## Known gaps', '']
    gaps = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'known_gaps.md')).read().strip() if os.path.exists(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'known_gaps.md')) else '(none recorded)'
    out.append(gaps)
    open(os.path.join(OUT, 'COVERAGE.md'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    print('COVERAGE.md written')

if __name__ == '__main__':
    main()
