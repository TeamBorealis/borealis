//! Embeds the bundled AI profile (`profile-assets/`) into the binary so installed profile files
//! can be verified against what this build shipped, not against a manifest in the same
//! user-writable directory.

use std::fs;
use std::path::{Path, PathBuf};

fn collect(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    let mut entries: Vec<_> = fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("read {}: {e}", dir.display()))
        .map(|e| e.expect("dir entry"))
        .collect();
    entries.sort_by_key(|e| e.file_name());
    for entry in entries {
        let path = entry.path();
        let ty = entry.file_type().expect("file type");
        if ty.is_dir() {
            collect(root, &path, out);
        } else if ty.is_file() {
            let rel = path
                .strip_prefix(root)
                .expect("under root")
                .components()
                .map(|c| c.as_os_str().to_string_lossy().into_owned())
                .collect::<Vec<_>>()
                .join("/");
            out.push((rel, path));
        } else {
            panic!("profile assets must be plain files: {}", path.display());
        }
    }
}

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("profile-assets");
    println!("cargo:rerun-if-changed={}", root.display());
    let mut files = Vec::new();
    collect(&root, &root, &mut files);
    let mut code = String::from(
        "/// Bundled profile files: (relative path, bytes). Generated by build.rs.\n\
         pub(crate) const BUNDLED_PROFILE: &[(&str, &[u8])] = &[\n",
    );
    for (rel, path) in &files {
        println!("cargo:rerun-if-changed={}", path.display());
        code.push_str(&format!(
            "    ({rel:?}, include_bytes!({:?})),\n",
            path.to_string_lossy()
        ));
    }
    code.push_str("];\n");
    let out =
        PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR")).join("bundled_profile.rs");
    fs::write(out, code).expect("write bundled_profile.rs");
}
